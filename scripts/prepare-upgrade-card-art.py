"""Build the upgrade card icon atlas from the two generated cutout sheets.

Run with: uv run --with pillow python scripts/prepare-upgrade-card-art.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "assets/upgrades/generated/raw"
ATLAS = ROOT / "assets/upgrades/render/upgrade-card-atlas.png"
METADATA = ROOT / "src/render/iso/gen/upgrade-card-atlas.ts"
PREVIEW = ROOT / "output/upgrade-card-art/contact-sheet.png"

SHEETS = {
    "weapons": (
        "meow-bolt", "moon-stars", "night-claw", "star-fall",
        "paper-crane", "pumpkin-seed", "watercolour-brush", "paper-cut",
        "page-fold", "echo-legion", "full-moon", None,
    ),
    "passives": (
        "vitality", "swift", "magnet", "focus",
        "scholar", "paper-armor", "night-eyes", "long-shadow",
        "deep-fold", "moon-shield", "snack", None,
    ),
}
SHEET_COLUMNS, SHEET_ROWS = 4, 3
ATLAS_COLUMNS = 6
DETAIL = 200
GUTTER = 4
ALPHA_FLOOR = 12


def crop_icon(tile: Image.Image, id: str | None) -> Image.Image | None:
    """Drop the nearly invisible fringe and return the art's tight bounds."""
    alpha = tile.getchannel("A").point(lambda a: a if a >= ALPHA_FLOOR else 0)
    bounds = alpha.getbbox()
    if id is None:
        if bounds is not None:
            raise ValueError(f"Expected a blank cell, found art at {bounds}")
        return None
    if bounds is None:
        raise ValueError(f"{id}: expected art in this cell")
    if min(bounds[2] - bounds[0], bounds[3] - bounds[1]) < 50:
        raise ValueError(f"{id}: cell contains only fragments at {bounds}")
    tile.putalpha(alpha)
    crop = tile.crop(bounds)
    crop.thumbnail((DETAIL, DETAIL), Image.Resampling.LANCZOS, reducing_gap=3)
    return crop


def extract() -> dict[str, Image.Image]:
    icons = {}
    for source, ids in SHEETS.items():
        with Image.open(RAW / f"{source}.png") as original:
            if "A" not in original.getbands() and "transparency" not in original.info:
                raise ValueError(f"{source}.png has no alpha channel")
            sheet = original.convert("RGBA")
        for index, id in enumerate(ids):
            row, col = divmod(index, SHEET_COLUMNS)
            box = (round(col * sheet.width / SHEET_COLUMNS), round(row * sheet.height / SHEET_ROWS),
                   round((col + 1) * sheet.width / SHEET_COLUMNS), round((row + 1) * sheet.height / SHEET_ROWS))
            icon = crop_icon(sheet.crop(box), id)
            if icon is not None:
                assert id not in icons
                icons[id] = icon
    return icons


def pack(icons: dict[str, Image.Image]) -> tuple[Image.Image, dict]:
    cell = DETAIL + 2 * GUTTER
    rows = (len(icons) + ATLAS_COLUMNS - 1) // ATLAS_COLUMNS
    atlas = Image.new("RGBA", (ATLAS_COLUMNS * cell, rows * cell))
    entries = {}
    for index, (id, icon) in enumerate(icons.items()):
        row, col = divmod(index, ATLAS_COLUMNS)
        w, h = icon.size
        x = col * cell + (cell - w) // 2
        y = row * cell + (cell - h) // 2
        atlas.paste(icon, (x, y))
        entries[id] = {"x": x, "y": y, "w": w, "h": h}
    return atlas, entries


def ts_source(entries: dict) -> str:
    lines = [f"  {json.dumps(id)}: {json.dumps(rect)}," for id, rect in entries.items()]
    return (
        "// Generated by scripts/prepare-upgrade-card-art.py.\n"
        "export interface UpgradeCardArtRect {\n"
        "  readonly x: number;\n  readonly y: number;\n"
        "  readonly w: number;\n  readonly h: number;\n}\n\n"
        "export const UPGRADE_CARD_ART: Readonly<Record<string, UpgradeCardArtRect>> = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )


def preview(icons: dict[str, Image.Image]) -> None:
    cell_w, cell_h, gap = 144, 135, 6
    sheet = Image.new("RGBA", (4 * cell_w, 6 * cell_h), "#0e192b")
    painter = ImageDraw.Draw(sheet)
    for group, ids in enumerate(SHEETS.values()):
        for i, id in enumerate(ids):
            if id is None:
                continue
            row, col = divmod(i, SHEET_COLUMNS)
            left, top = col * cell_w, (group * SHEET_ROWS + row) * cell_h
            painter.rounded_rectangle((left + gap, top + gap, left + cell_w - gap, top + cell_h - gap),
                                      9, fill="#17253b", outline="#314460")
            icon = icons[id].copy()
            icon.thumbnail((95, 95), Image.Resampling.LANCZOS)
            sheet.alpha_composite(icon, (left + (cell_w - icon.width) // 2, top + 11 + (95 - icon.height) // 2))
            painter.text((left + cell_w // 2, top + 114), id, fill="#dcd4bb", anchor="mt")
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(PREVIEW)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated files without rewriting them")
    parser.add_argument("--preview", action="store_true", help="write a labeled contact sheet on navy")
    args = parser.parse_args()
    icons = extract()
    assert len(icons) == 22
    atlas, entries = pack(icons)
    metadata = ts_source(entries)
    if args.check:
        with Image.open(ATLAS) as current:
            if current.mode != "RGBA" or current.size != atlas.size:
                raise ValueError("Upgrade atlas dimensions or alpha format differ")
            if ImageChops.difference(current, atlas).getbbox(alpha_only=False):
                raise ValueError("Upgrade atlas pixels differ")
        if METADATA.read_text(encoding="utf-8") != metadata:
            raise ValueError("Upgrade atlas metadata differs")
    else:
        ATLAS.parent.mkdir(parents=True, exist_ok=True)
        atlas.save(ATLAS, optimize=True)
        METADATA.write_text(metadata, encoding="utf-8")
    if args.preview:
        preview(icons)


if __name__ == "__main__":
    main()
