#!/usr/bin/env node
// Dumps the inputs of the voxel scenery bake (scripts/iso-art/build.py) from the compiled game
// (run `npm run build` first): the material ramps of src/render/iso/palette.ts, the colours the
// terrain already uses, and the yard footprints the sprites must fit (src/render/iso/yard-models.ts,
// src/game/scenery.ts). Writes scripts/iso-art/inputs.json, which is committed so the Python bake
// runs without dist/.
//
//   node scripts/iso-art/dump-inputs.mjs
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DIST = resolve(HERE, "../../dist");
const imp = (p) => import(join(DIST, p));
const { ISO_RAMPS, isoPaletteColours } = await imp("render/iso/palette.js");
const { isoYardPieces } = await imp("render/iso/yard-models.js");
const { SOLID_SCENERY } = await imp("game/scenery.js");
const { YARD_PROPS, LAMPS } = await imp("render/scene.js");

const bases = {};
for (const p of isoYardPieces()) bases[p.sprite] ??= p.base;
// The two front-on fences of the old yard decor stand on the first two SOLID_SCENERY capsules.
const fences = YARD_PROPS.filter((p) => p.kind === "fence").map((p) => {
  const c = SOLID_SCENERY.find((s) => s.y1 === p.y && s.x1 < p.x && s.x2 > p.x);
  return { x: p.x, y: p.y, base: { x: c.x1 - c.radius - p.x, y: c.y1 - c.radius - p.y, w: c.x2 - c.x1 + 2 * c.radius, d: 2 * c.radius } };
});
// Cat identity for the voxel puppets (scripts/iso-art/puppet.py): the official head palette and
// accessories (src/cats/, read only) and the clothing palette of each cat's art definition.
const { CAT_ART } = await imp("render/art-index.js");
const { officialVariant } = await imp("cats/official.js");
const cats = {};
for (const art of CAT_ART.all()) {
  const o = officialVariant(art.id);
  cats[art.id] = { palette: o.palette, accessories: o.accessories ?? [], body: art.body };
}
// Costume identity for the voxel costume layers (scripts/iso-art/costumes.py): wardrobe colours, makeup and the
// garment palette of each costume's art definition. The part geometry is authored in the bake script.
const { COSTUME_ART } = await imp("render/art-index.js");
const costumes = {};
for (const art of COSTUME_ART.all())
  costumes[art.id] = {
    colors: art.colors,
    expression: art.makeup.expression ?? "idle",
    accessories: art.makeup.accessories ?? [],
    patches: (art.makeup.patches ?? []).map((patch) => patch.color),
    coat: art.outfit.coat ?? {},
    tee: art.outfit.tee ?? {},
  };
const out = {
  note: "Generated by scripts/iso-art/dump-inputs.mjs from dist/; inputs of scripts/iso-art/build.py.",
  ramps: ISO_RAMPS,
  terrainColours: isoPaletteColours(),
  bases,
  fences,
  lamps: LAMPS.map((l) => l.s),
  cats,
  costumes,
};
writeFileSync(join(HERE, "inputs.json"), JSON.stringify(out, null, 1) + "\n");
console.log(`inputs.json: ${Object.keys(bases).length} yard sprites, ${fences.length} fences`);
