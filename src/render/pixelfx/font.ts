export interface Glyph { w: number; rows: boolean[][]; }
export interface PixelFont { h: number; space: number; gap: number; glyphs: Record<string, Glyph>; }
export type FontName = 'mini' | 'big';

function build(table: Record<string, string>, h: number): Record<string, Glyph> {
  const out: Record<string, Glyph> = {};
  for (const [ch, src] of Object.entries(table)) {
    const rows = src.split('|');
    out[ch] = { w: (rows[0] ?? '').length, rows: rows.map((r) => [...r].map((c) => c === '#')) };
    if (rows.length !== h) throw new Error(`glyph ${ch} has ${rows.length} rows, expected ${h}`);
  }
  return out;
}

export const FONTS: Record<FontName, PixelFont> = {
  mini: { h: 5, space: 2, gap: 1, glyphs: build(MINI, 5) },
  big: { h: 7, space: 3, gap: 1, glyphs: build(BIG, 7) },
};

const glyphOf = (F: PixelFont, ch: string): Glyph | undefined => F.glyphs[ch] ?? F.glyphs[ch.toUpperCase()];

/** Width in font pixels of a string (before scaling). */
export function textWidth(str: string | number, font: FontName = 'mini'): number {
  const F = FONTS[font];
  let w = 0;
  for (const ch of String(str)) {
    const g = glyphOf(F, ch);
    w += (g ? g.w : F.space) + F.gap;
  }
  return Math.max(0, w - F.gap);
}

/** Calls plot(x, y) for every inked font pixel of str, with the top-left of the text at (0, 0). */
export function rasterText(str: string | number, font: FontName, plot: (x: number, y: number) => void): void {
  const F = FONTS[font];
  let x = 0;
  for (const ch of String(str)) {
    const g = glyphOf(F, ch);
    if (!g) {
      x += F.space + F.gap;
      continue;
    }
    for (let r = 0; r < F.h; r++) for (let c = 0; c < g.w; c++) if (g.rows[r]?.[c]) plot(x + c, r);
    x += g.w + F.gap;
  }
}
